// RNG xorshift128 deterministik (benih tetap) agar hasil emulator dapat diulang
static uint32_t rs[4] = {0x12345678u, 0x9ABCDEF0u, 0x0F1E2D3Cu, 0x4B5A6978u};
static uint32_t xorshift128(void) {
  uint32_t t = rs[3], s = rs[0];
  rs[3] = rs[2]; rs[2] = rs[1]; rs[1] = s;
  t ^= t << 11; t ^= t >> 8;
  return rs[0] = t ^ s ^ (s >> 19);
}
static void rng_fill(uint8_t *dest, size_t size) {
  while (size) { uint32_t r = xorshift128();
    for (int i = 0; i < 4 && size; i++, size--) { *dest++ = (uint8_t)r; r >>= 8; } }
}
